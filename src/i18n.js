export function normalizeLocale(locale) { return locale === 'en' ? 'en' : 'zh-CN'; }
export function preferredLocale() {
  try { const saved = localStorage.getItem('git-history-locale'); if (saved === 'en' || saved === 'zh-CN') return saved; } catch {}
  return (navigator.languages?.[0] || navigator.language || 'en').toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}
const numbers = Object.fromEntries(['zh-CN', 'en'].map(locale => [locale, new Intl.NumberFormat(locale)]));
export function t(locale, key, params = {}) {
  const text = messages[normalizeLocale(locale)][key] ?? messages['zh-CN'][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => typeof params[name] === 'number' ? numbers[normalizeLocale(locale)].format(params[name]) : String(params[name] ?? `{${name}}`));
}
export function applyTranslations(document, locale) {
  document.documentElement.lang = normalizeLocale(locale);
  for (const element of document.querySelectorAll('[data-i18n]')) element.textContent = t(locale, element.dataset.i18n);
  for (const attribute of ['placeholder', 'aria-label']) {
    for (const element of document.querySelectorAll(`[data-i18n-${attribute}]`)) element.setAttribute(attribute, t(locale, element.getAttribute(`data-i18n-${attribute}`)));
  }
}
export class AppError extends Error {
  constructor(code, params = {}) { super(t('zh-CN', code, params)); this.code = code; this.params = params; }
}
